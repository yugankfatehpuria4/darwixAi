import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { CallState, TurnLatency } from "../src/agent/types";

// Reads every stored call under runtime/calls and reports per-hop latency.
// Run after scripted calls (npm run scenarios) and after browser calls, which
// are the only source of ASR and TTS timings.
const directory = path.resolve("runtime/calls");
const files = (await readdir(directory).catch(() => [])).filter((file) => file.endsWith(".json"));
const calls: CallState[] = await Promise.all(files.map(async (file) => JSON.parse(await readFile(path.join(directory, file), "utf8"))));
const rows: Array<TurnLatency & { market: string; llm_used: boolean }> = calls.flatMap((call) =>
  call.latencies.map((latency) => ({ ...latency, market: call.market, llm_used: latency.llm_ms !== undefined })),
);

function percentile(values: number[], p: number): number | null {
  if (!values.length) return null;
  const sorted = [...values].sort((a, b) => a - b);
  // Nearest-rank: the smallest value with at least p% of samples at or below it.
  return sorted[Math.max(0, Math.ceil((p / 100) * sorted.length) - 1)];
}

const hops: Array<[keyof TurnLatency, string, string]> = [
  ["asr_ms", "ASR (browser)", "end of caller speech to final transcript, measured in the browser"],
  ["understand_ms", "Understanding + rules", "intent, slot extraction, business rules, reply assembly"],
  ["retrieval_ms", "Retrieval", "hybrid search over the KB, only on turns that query it"],
  ["llm_ms", "LLM", "Gemini grounded answer, only on turns that used it"],
  ["server_total_ms", "Server total", "request in to reply out, all of the above except ASR/TTS"],
  ["tts_start_ms", "TTS start (browser)", "reply received to first audio from the browser voice"],
];

const format = (value: number | null) => (value === null ? "n/a" : `${value} ms`);
const lines = [
  "# Q1/Q3 voice agent latency",
  "",
  `Generated by \`npm run report:latency\` from ${calls.length} stored calls (${rows.length} customer turns) in runtime/calls on ${new Date().toISOString().slice(0, 10)}.`,
  "Percentiles are nearest-rank over turns. A hop with n = 0 was not exercised by any stored call; its number is not estimated.",
  "",
  "| Hop | n | p50 | p95 | max | What it covers |",
  "|---|---|---|---|---|---|",
];
for (const [key, label, covers] of hops) {
  const values = rows.map((row) => row[key]).filter((value): value is number => typeof value === "number");
  lines.push(`| ${label} | ${values.length} | ${format(percentile(values, 50))} | ${format(percentile(values, 95))} | ${format(values.length ? Math.max(...values) : null)} | ${covers} |`);
}
lines.push("", "## By market (server total)", "", "| Market | n | p50 | p95 |", "|---|---|---|---|");
for (const market of ["in_health", "ph_life", "id_finance"]) {
  const values = rows.filter((row) => row.market === market).map((row) => row.server_total_ms);
  lines.push(`| ${market} | ${values.length} | ${format(percentile(values, 50))} | ${format(percentile(values, 95))} |`);
}
const llmTurns = rows.filter((row) => row.llm_used).length;
lines.push(
  "",
  "## Reading this",
  "",
  `- Turns that used the LLM: ${llmTurns}. With no GEMINI_API_KEY (or no network route to Google) every grounded answer is extractive, so the LLM row reflects only failed or skipped calls.`,
  "- ASR and TTS happen in the caller's browser. Scripted runs inject text at the ASR output, so those rows only fill in from real browser calls.",
  "- End-to-end turn latency for a live call = ASR + server total + TTS start (plus network). The budget we designed against is in docs/architecture.md.",
);

await mkdir("evidence/q1", { recursive: true });
await writeFile("evidence/q1/latency.md", `${lines.join("\n")}\n`);
console.log(lines.join("\n"));
