import { mkdir, readFile, writeFile } from "node:fs/promises";
import { startCall } from "../src/agent/dialogue";
import { PACKS } from "../src/agent/session";
import { looksLikeQuestion, yesNo } from "../src/agent/parse";
import type { Market } from "../src/kb/types";

interface Utterance {
  market: Market;
  kind: string;
  text: string;
  expect: { register?: string; slot?: string; intent?: string };
}

const { items }: { items: Utterance[] } = JSON.parse(await readFile("data/eval/q3-language-eval.json", "utf8"));
const clock = new Date("2026-10-02T03:00:00Z");

function intentOf(market: Market, text: string): string {
  const pack = PACKS[market];
  if (pack.patterns.escalation.test(text)) return "escalation";
  const objection = pack.objections.find((candidate) => candidate.pattern.test(text) && !candidate.unless?.test(text));
  if (objection) return objection.id;
  const { state } = startCall(pack, clock);
  const hardship = pack.slots.some((slot) => slot.extract(text, false, state) === "hardship");
  if (hardship) return "hardship";
  if (looksLikeQuestion(text)) return "question";
  const answer = yesNo(text);
  return answer ?? "none";
}

function slotOf(market: Market, text: string, slotName: string): string {
  const pack = PACKS[market];
  const { state } = startCall(pack, clock);
  const slot = pack.slots.find((candidate) => candidate.name === slotName)!;
  return String(slot.extract(text, true, state));
}

const rows: string[] = [];
const tally = new Map<string, { checks: number; passed: number }>();
const count = (key: string, ok: boolean) => {
  const entry = tally.get(key) ?? { checks: 0, passed: 0 };
  entry.checks++;
  if (ok) entry.passed++;
  tally.set(key, entry);
};

for (const utterance of items) {
  const pack = PACKS[utterance.market];
  const results: string[] = [];
  let allOk = true;
  if (utterance.expect.register) {
    const register = pack.detectRegister(utterance.text, pack.default_register);
    const ok = register === utterance.expect.register;
    count(`${utterance.market} register`, ok);
    allOk &&= ok;
    results.push(`register ${register}${ok ? "" : ` (expected ${utterance.expect.register})`}`);
  }
  if (utterance.expect.intent) {
    const intent = intentOf(utterance.market, utterance.text);
    const ok = intent === utterance.expect.intent;
    count(`${utterance.market} intent`, ok);
    allOk &&= ok;
    results.push(`intent ${intent}${ok ? "" : ` (expected ${utterance.expect.intent})`}`);
  }
  if (utterance.expect.slot) {
    const [name, expected] = utterance.expect.slot.split("=");
    const value = slotOf(utterance.market, utterance.text, name);
    const ok = value === expected;
    count(`${utterance.market} slot`, ok);
    allOk &&= ok;
    results.push(`${name}=${value}${ok ? "" : ` (expected ${expected})`}`);
  }
  count(`${utterance.market} ${utterance.kind} (utterances)`, allOk);
  rows.push(`| ${utterance.market} | ${utterance.kind} | ${utterance.text} | ${results.join("; ")} | ${allOk ? "pass" : "FAIL"} |`);
}

const pct = (entry: { checks: number; passed: number }) => `${entry.passed}/${entry.checks} (${((entry.passed / entry.checks) * 100).toFixed(0)}%)`;
const output = [
  "# Q3 understanding eval: register, intent and slot extraction",
  "",
  `Generated by \`npm run eval:language\` over \`data/eval/q3-language-eval.json\` (${items.length} utterances, call date fixed at 2026-10-02). These are written by us, not by native speakers; they check that the lexicons and rules do what we intended on code-switched and regional input, not that they cover real speech (see GAPS.md GAP-005).`,
  "",
  "| Check | Passed |",
  "|---|---|",
  ...[...tally.entries()].sort().map(([key, entry]) => `| ${key} | ${pct(entry)} |`),
  "",
  "| Market | Kind | Utterance | Result | |",
  "|---|---|---|---|---|",
  ...rows,
  "",
].join("\n");
await mkdir("evidence/q3", { recursive: true });
await writeFile("evidence/q3/language_eval.md", output);
console.log(output);
