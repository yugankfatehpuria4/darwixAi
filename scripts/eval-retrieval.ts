import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { DEFAULT_MIN_CONFIDENCE, search, type SearchOptions, type SearchResult } from "../src/kb/search";
import type { Market } from "../src/kb/types";

interface EvalQuestion {
  id: string;
  market: Market;
  type: string;
  language?: string;
  query: string;
  answerable: boolean;
  expected: Array<{ source: string; section: string }>;
}

const evalSet: { items: EvalQuestion[] } = JSON.parse(await readFile("data/eval/retrieval-eval.json", "utf8"));
const holdout: { items: EvalQuestion[] } = JSON.parse(await readFile("data/eval/retrieval-holdout.json", "utf8"));
const glossaryHash = createHash("sha256").update(await readFile("data/glossary.json")).digest("hex").slice(0, 12);

const isExpected = (question: EvalQuestion, source: string, section: string) =>
  question.expected.some((expected) => source.endsWith(expected.source) && section.toLowerCase().includes(expected.section.toLowerCase()));

function firstRelevantRank(question: EvalQuestion, result: SearchResult): number | null {
  const hit = result.hits.find((candidate) => isExpected(question, candidate.record.source, candidate.record.section));
  return hit ? hit.rank : null;
}

interface Metrics {
  n: number;
  hit1: number;
  hit3: number;
  mrr: number;
}

function retrievalMetrics(items: EvalQuestion[], options: Omit<SearchOptions, "market">): Metrics {
  const answerable = items.filter((question) => question.answerable);
  let hit1 = 0;
  let hit3 = 0;
  let reciprocal = 0;
  for (const question of answerable) {
    const rank = firstRelevantRank(question, search(question.query, { ...options, market: question.market, topK: 5 }));
    if (rank === 1) hit1++;
    if (rank !== null && rank <= 3) hit3++;
    if (rank !== null) reciprocal += 1 / rank;
  }
  const n = answerable.length;
  return { n, hit1: hit1 / n, hit3: hit3 / n, mrr: reciprocal / n };
}

/**
 * At a given threshold: of the answerable questions, how many does the bot
 * answer with a correct top-1 chunk (useful answers), how many does it
 * answer wrongly (the dangerous case), and how many out-of-scope questions
 * does it correctly refuse.
 */
function gateMetrics(items: EvalQuestion[], threshold: number) {
  let answeredCorrect = 0;
  let answeredWrong = 0;
  let refusedAnswerable = 0;
  let refusedOutOfScope = 0;
  let answeredOutOfScope = 0;
  for (const question of items) {
    const result = search(question.query, { market: question.market, topK: 5, minConfidence: threshold });
    const top1Correct = firstRelevantRank(question, result) === 1;
    if (question.answerable) {
      if (!result.answerable) refusedAnswerable++;
      else if (top1Correct) answeredCorrect++;
      else answeredWrong++;
    } else if (result.answerable) answeredOutOfScope++;
    else refusedOutOfScope++;
  }
  const answered = answeredCorrect + answeredWrong + answeredOutOfScope;
  return {
    threshold,
    answered_precision: answered ? answeredCorrect / answered : 0,
    answerable_recall: answeredCorrect / items.filter((question) => question.answerable).length,
    out_of_scope_refusal: refusedOutOfScope / Math.max(1, items.filter((question) => !question.answerable).length),
    answeredCorrect,
    answeredWrong,
    refusedAnswerable,
    refusedOutOfScope,
    answeredOutOfScope,
  };
}

