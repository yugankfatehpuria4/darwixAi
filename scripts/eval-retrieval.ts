/** Deterministic ASR-style damage: drop one inner letter from every other long word. */
function damage(query: string): string {
  let longWords = 0;
  return query
    .split(" ")
    .map((word) => {
      if (word.replace(/\W/g, "").length < 5) return word;
      longWords++;
      if (longWords % 2) return word;
      const middle = Math.floor(word.length / 2);
      return word.slice(0, middle) + word.slice(middle + 1);
    })
    .join(" ");
}

